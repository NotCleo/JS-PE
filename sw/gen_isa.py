#!/usr/bin/env python3
# isa.yaml -> sw/isa_def.py, src/jspe_isa.vh, formal/jspe_fv_isa.vh; --check verifies all are up to date and self-checks the encoding.
import os, sys, pprint, yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
YAML = os.path.join(ROOT, "docs", "spec", "isa.yaml")
PY_OUT = os.path.join(ROOT, "sw", "isa_def.py")
VH_OUT = os.path.join(ROOT, "src", "jspe_isa.vh")
FV_OUT = os.path.join(ROOT, "formal", "jspe_fv_isa.vh")
HDR = "generated by sw/gen_isa.py from docs/spec/isa.yaml, do not edit"


def load(path=YAML):
    with open(path) as f:
        return yaml.safe_load(f)


def fmask(fields):
    m = 0
    for name, (hi, lo) in fields.items():
        m |= ((1 << (hi - lo + 1)) - 1) << lo
    return m


def self_check(d):
    errs = []
    ins = d["instructions"]
    names = set()
    for i in ins:
        if i["name"] in names:
            errs.append("duplicate name " + i["name"])
        names.add(i["name"])
        fm = fmask(i.get("fields", {}))
        if fm & i["mask"]:
            errs.append("%s: field overlaps mask" % i["name"])
        if (fm | i["mask"]) != 0xFFFF:
            errs.append("%s: bits not covered %04x" % (i["name"], 0xFFFF & ~(fm | i["mask"])))
        if i["value"] & ~i["mask"]:
            errs.append("%s: value outside mask" % i["name"])
        f = d["formats"][i["format"]]
        if (i["value"] & f["mask"]) != f["value"]:
            errs.append("%s: value not in format %s" % (i["name"], i["format"]))
        if f["guarded"] and i.get("fields", {}).get("g") != [3, 0]:
            errs.append("%s: guarded format without g at [3:0]" % i["name"])
    table = decode_table(d)
    for w, hits in enumerate(table):
        if len(hits) > 1:
            errs.append("collision at %04x: %s" % (w, hits))
            break
    undef = sum(1 for h in table if not h)
    return errs, undef


def decode_table(d):
    ins = d["instructions"]
    und = d.get("undefined", [])
    out = []
    for w in range(65536):
        if any((w & u["mask"]) == u["value"] for u in und):
            out.append([])
            continue
        out.append([i["name"] for i in ins if (w & i["mask"]) == i["value"]])
    return out


def gen_py(d):
    body = "# " + HDR + "\n"
    body += "ISA = " + pprint.pformat(d, width=110, sort_dicts=False) + "\n"
    return body


def vname(s):
    return str(s).upper().replace("-", "_")


def lp(name, width, val):
    return "localparam [%d:0] %s = %d'h%X;\n" % (width - 1, name, width, val)


def gen_vh(d):
    o = ["// " + HDR + "\n", "// localparams for inclusion inside a module: no include guard, every module needs its own copy\n"]
    pre = {"guard": ("G", 4), "reg": ("REG", 3), "reg2": ("REG2", 2), "act_a": ("ACTA", 3), "act_b": ("ACTB", 2),
           "loop": ("LOOP", 2), "cond_src": ("COND", 4), "alu": ("ALU", 4), "imm_op": ("IMM", 2), "mem_mode": ("MEM", 2),
           "cc_sel": ("CCSEL", 4), "cc_mode": ("CCMODE", 2), "alt": ("ALT", 2), "timer_pre": ("TPRE", 2),
           "sync_edge": ("SEDGE", 2), "bind_src": ("BSRC", 5)}
    for en, vals in d["enums"].items():
        p, w = pre[en]
        for k, v in vals.items():
            o.append(lp("%s_%s" % (p, vname(k)), w, v))
    for fn, f in d["formats"].items():
        o.append(lp("FMT_%s_MASK" % fn, 16, f["mask"]))
        o.append(lp("FMT_%s_VAL" % fn, 16, f["value"]))
    for i in d["instructions"]:
        o.append(lp("I_%s_MASK" % vname(i["name"]), 16, i["mask"]))
        o.append(lp("I_%s_VAL" % vname(i["name"]), 16, i["value"]))
    for k, u in enumerate(d.get("undefined", [])):
        o.append(lp("UNDEF%d_MASK" % k, 16, u["mask"]))
        o.append(lp("UNDEF%d_VAL" % k, 16, u["value"]))
    for c in d["cregs"]:
        o.append(lp("CREG_%s" % c["name"], 5, c["index"]))
        if c.get("reset") is not None:
            o.append(lp("CREG_%s_RESET" % c["name"], 16, c["reset"]))
    h = d["host"]
    o.append(lp("H_ESC", 8, h["esc"]))
    for k, v in h["h2c"].items():
        o.append(lp("H2C_%s" % vname(k), 8, v))
    for k, v in h["c2h"].items():
        o.append(lp("C2H_%s" % vname(k), 8, v))
    for k, r in h["regs"].items():
        o.append(lp("HREG_%s" % vname(k), 8, r["addr"]))
        if r.get("reset") is not None:
            o.append(lp("HREG_%s_RESET" % vname(k), 16, r["reset"]))
    for k, v in h["image"].items():
        o.append(lp("IMG_%s" % vname(k), 8, v))
    return "".join(o)


def gen_fv(d):
    o = ["// " + HDR + "\n",
         "// decoder predicate for formal/fv_seq_dec.v: undefined = no instruction matches, or an undefined group matches\n",
         "function fv_undef;\n", "  input [15:0] w;\n", "  begin\n", "    fv_undef = 1'b1;\n"]
    for i in d["instructions"]:
        o.append("    if ((w & 16'h%04X) == 16'h%04X) fv_undef = 1'b0;  // %s\n" % (i["mask"], i["value"], i["name"]))
    for u in d.get("undefined", []):
        o.append("    if ((w & 16'h%04X) == 16'h%04X) fv_undef = 1'b1;  // undefined group\n" % (u["mask"], u["value"]))
    o += ["  end\n", "endfunction\n"]
    return "".join(o)


def main(argv):
    d = load()
    errs, undef = self_check(d)
    for e in errs:
        print("isa.yaml:", e)
    py, vh, fv = gen_py(d), gen_vh(d), gen_fv(d)
    if "--check" in argv:
        stale = [p for p, txt in ((PY_OUT, py), (VH_OUT, vh), (FV_OUT, fv)) if not os.path.exists(p) or open(p).read() != txt]
        for p in stale:
            print("stale:", os.path.relpath(p, ROOT))
        print("%d instructions, %d undefined words, %d errors" % (len(d["instructions"]), undef, len(errs)))
        return 1 if errs or stale else 0
    if errs:
        return 1
    for p, txt in ((PY_OUT, py), (VH_OUT, vh), (FV_OUT, fv)):
        with open(p, "w") as f:
            f.write(txt)
    print("%d instructions, %d undefined words" % (len(d["instructions"]), undef))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
