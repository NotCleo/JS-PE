#!/usr/bin/env python3
# make mutate B=<block>: plant each RTL mutant of formal/mutants/<block>.yaml, run its prove task(s) of formal/<block>.sby,
# report tried / caught / survivors -> terminal, build/formal/mutate_<block>.txt and the Mutants list in formal/RESULTS.md
import concurrent.futures as cf, datetime, os, re, shutil, subprocess, sys
import yaml

BUILD = "build/formal"
HEAD = ("Mutants (generated by `make mutate B=<block>` from formal/mutants/<block>.yaml; caught = a prove task fails "
        "with a counterexample; equivalent survivors carry their reason in that file):")


def apply_edits(src, m):
    for e in m.get("edits") or [{"old": m["old"], "new": m["new"]}]:
        n = src.count(e["old"])
        if n != 1:
            return None, f"pattern matches {n} times: {e['old'][:50]!r}"
        src = src.replace(e["old"], e["new"])
    return src, ""


def run(block, cfg, sby, files, i, m):
    name = m["name"]
    tasks = m.get("tasks") or ([m["task"]] if "task" in m else cfg["tasks"])
    src, err = apply_edits(open(f"src/{cfg['rtl']}").read(), m)
    if src is None:
        return name, "error", err
    d = os.path.join(BUILD, f"mut_{block}", f"{i:02d}_{name}")
    os.makedirs(d)
    for f in files:
        p = os.path.normpath(os.path.join("formal", f))
        txt = src if os.path.basename(p) == cfg["rtl"] else open(p).read()
        open(os.path.join(d, os.path.basename(p)), "w").write(txt)
    s = sby.split("[files]")[0] + "[files]\n" + "\n".join(os.path.basename(f) for f in files) + "\n"
    depth = m.get("depth", cfg.get("depth"))
    if depth:
        for t in tasks:
            s = re.sub(rf"(?m)^{t}: depth \d+", f"{t}: depth {depth}", s)
    open(os.path.join(d, f"{block}.sby"), "w").write(s)
    try:
        out = subprocess.run(["sby", "-f", f"{block}.sby"] + tasks, cwd=d, capture_output=True, text=True,
                             timeout=cfg.get("timeout", 3600)).stdout
    except subprocess.TimeoutExpired:
        return name, "error", "timeout"
    st = {t: (re.findall(rf"\[{block}_{t}\] DONE \((\w+)", out) or ["ERROR"])[-1] for t in tasks}
    failed = sorted({n.rsplit(".", 1)[-1] for n in re.findall(r"failed assertion (\S+(?: \.\w+)?) at", out)})
    if "FAIL" in st.values():
        return name, "caught", " ".join(failed)
    if "UNKNOWN" in st.values():
        return name, "unproven", f"induction fails, no trace at base depth {depth or 'of the .sby'} ({' '.join(failed)})"
    if all(v == "PASS" for v in st.values()):
        return name, "survivor", ("equivalent: " + m["equivalent"]) if "equivalent" in m else "NOT EXPLAINED"
    return name, "error", " ".join(f"{t}={v}" for t, v in st.items())


def update_results(block, line):
    path = "formal/RESULTS.md"
    text = open(path).read()
    i = text.find("\n## ")
    head, rest = (text[:i], text[i:]) if i >= 0 else (text, "")
    lines = head.rstrip("\n").split("\n")
    if HEAD not in lines:
        lines += ["", HEAD]
    k = lines.index(HEAD) + 1
    j = k
    while j < len(lines) and lines[j].startswith("- "):
        j += 1
    items = {l[2:].split(":", 1)[0]: l for l in lines[k:j]}
    items[block] = f"- {block}: {line}"
    lines[k:j] = [items[b] for b in sorted(items)]
    open(path, "w").write("\n".join(lines) + "\n" + rest)


def main(block):
    cfg = yaml.safe_load(open(f"formal/mutants/{block}.yaml"))
    sby = open(f"formal/{block}.sby").read()
    files = [l.strip() for l in sby.split("[files]")[1].splitlines() if l.strip()]
    shutil.rmtree(os.path.join(BUILD, f"mut_{block}"), ignore_errors=True)
    muts = cfg["mutants"]
    with cf.ThreadPoolExecutor(max_workers=int(os.environ.get("MUT_J", "8"))) as ex:
        res = list(ex.map(lambda a: run(block, cfg, sby, files, *a), enumerate(muts)))
    with open(os.path.join(BUILD, f"mutate_{block}.txt"), "w") as f:
        for name, st, why in res:
            f.write(f"{name:<24} {st:<9} {why}\n")
    n = {k: sum(st == k for _, st, _ in res) for k in ("caught", "survivor", "unproven", "error")}
    eq = [name for name, st, why in res if st == "survivor" and why.startswith("equivalent")]
    print(f"{block}: {len(res)} tried, {n['caught']} caught, {n['survivor']} survivors ({len(eq)} equivalent), "
          f"{n['unproven']} unproven, {n['error']} errors (details {BUILD}/mutate_{block}.txt)")
    for name, st, why in res:
        if st != "caught":
            print(f"  {st:<9} {name}: {why}")
    surv = f", {n['survivor']} survivors ({len(eq)} equivalent: {', '.join(eq)})" if n["survivor"] else ""
    bad = f", {n['unproven']} unproven, {n['error']} errors" if n["unproven"] or n["error"] else ""
    update_results(block, f"{len(res)} tried, {n['caught']} caught{surv}{bad} ({datetime.date.today()})")
    return 0 if n["caught"] + len(eq) == len(res) else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1]))
